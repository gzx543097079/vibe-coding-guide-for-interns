const { sleep, snap, diff, q, qs, ev, center, key, rect, drag, up } = V
const out = []
const cs = (e) => e.ownerDocument.defaultView.getComputedStyle(e)
const full = (r) => [...r.querySelectorAll('*')].find((e) => cs(e).fontSize === '74px')
const dim = (r) => [...r.querySelectorAll('*')].find((e) => cs(e).backgroundColor === 'rgb(0, 0, 0)' && e.getBoundingClientRect().height > 400)
const dlg = (r) => r.querySelector('[role="dialog"]')
const act = (r) => r.ownerDocument.activeElement?.getAttribute('aria-label')
const both = (f) => [A, B].map(f).join('  |  ')
let [A, B] = await V.pair('zoom')
out.push('网格布局 ' + diff(snap(A), snap(B)))
out.push('缩略图 5 位置 ' + both((r) => rect(r, q(r, '查看第 5 张照片'))))
for (const r of [A, B]) q(r, '查看第 5 张照片').click()
await new Promise((r) => requestAnimationFrame(() => r()))
out.push('打开首帧大图 ' + both((r) => (full(r) ? rect(r, full(r)) + ' r=' + cs(full(r)).borderRadius : '无')))
await sleep(120)
out.push('打开 120ms 大图 ' + both((r) => rect(r, full(r)) + ' 遮罩 ' + (+cs(dim(r)).opacity).toFixed(2)))
await sleep(450)
out.push('全屏 大图 ' + both((r) => rect(r, full(r)) + ' r=' + cs(full(r)).borderRadius + ' 遮罩 ' + cs(dim(r)).opacity))
out.push('全屏布局 ' + diff(snap(A), snap(B)))
out.push('焦点 ' + both(act) + ' ；dialog ' + both((r) => dlg(r)?.getAttribute('aria-label') + ' modal=' + dlg(r)?.getAttribute('aria-modal')) + ' ；缩略图 5 ' + both((r) => cs(q(r, '查看第 5 张照片')).visibility))
for (const r of [A, B]) await drag(full(r), 20, 120, false)
await sleep(60)
out.push('向下拖 (20,120) 大图 ' + both((r) => rect(r, full(r)) + ' 遮罩 ' + (+cs(dim(r)).opacity).toFixed(2)))
for (const r of [A, B]) up(full(r), 20, 120)
await sleep(120)
out.push('松手 120ms 大图 ' + both((r) => (full(r) ? rect(r, full(r)) : '已移除')))
await sleep(400)
out.push('关闭后 dialog ' + both((r) => !!dlg(r)) + ' 焦点 ' + both(act) + ' 缩略图 5 ' + both((r) => cs(q(r, '查看第 5 张照片')).visibility))
for (const r of [A, B]) q(r, '查看第 2 张照片').click()
await sleep(500)
for (const r of [A, B]) await drag(full(r), 0, 50, true)
await sleep(450)
out.push('拖 50 松手回弹 大图 ' + both((r) => (full(r) ? rect(r, full(r)) + ' 遮罩 ' + cs(dim(r)).opacity : '已关闭')))
for (const r of [A, B]) await drag(full(r), 0, -60, false)
await sleep(60)
out.push('向上拖 60 大图 ' + both((r) => rect(r, full(r)) + ' 遮罩 ' + cs(dim(r)).opacity))
for (const r of [A, B]) up(full(r), 0, -60)
await sleep(450)
for (const r of [A, B]) key(r.ownerDocument.activeElement, 'Escape')
await sleep(450)
out.push('Esc 后 dialog ' + both((r) => !!dlg(r)) + ' 焦点 ' + both(act))
for (const r of [A, B]) q(r, '查看第 6 张照片').click()
await sleep(500)
for (const r of [A, B]) q(r, '关闭').click()
await sleep(450)
out.push('关闭按钮后 dialog ' + both((r) => !!dlg(r)) + ' 焦点 ' + both(act))
;[A, B] = await V.pair('zoom', true)
out.push('深色网格 ' + diff(snap(A), snap(B)))
for (const r of [A, B]) q(r, '查看第 3 张照片').click()
await sleep(550)
out.push('深色全屏 ' + diff(snap(A), snap(B)))
return out.join('\n')
